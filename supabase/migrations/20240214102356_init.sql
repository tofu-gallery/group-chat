-- Tofu changed this file on 2026-10-25 (TOFU.md says why, in full):
--   * Roles come from public.app_members, one row per email address (admin, member or viewer), which Tofu's dashboard
--     shows and sets; the first account made in the app becomes its admin. Upstream read a custom claim that an auth
--     hook added to each sign-in, and made anyone whose address contained +supaadmin@ or +supamod@ an admin or a
--     moderator, so anyone could promote themselves. A viewer can read but not post. A later file,
--     20261025200000_tofu_roles_follow_address_changes.sql, moves a person's row when their address changes and
--     replaces handle_new_user below, so a new account never takes over a role left on its address.
--   * public.create_user() is gone: a SECURITY DEFINER function in public, callable by anyone through the Data API,
--     that wrote accounts straight into auth.users.
--   * The realtime publication is added to, never dropped and made again.
--   * Removing a person removes their profile, their messages and their role; channels they made stay, with no creator.
--   * People cannot rename themselves through the Data API (the trigger below names each profile after its address).
--   * The Data API's roles get exactly the privileges the app's pages use, and every table has row-level security.
--   * A sign-up switch (public.app_settings) that the database itself enforces.
--

-- Custom types
create type public.app_permission as enum ('channels.create', 'channels.delete', 'messages.create', 'messages.delete');
create type public.user_status as enum ('ONLINE', 'OFFLINE');

-- USERS
create table public.users (
  id          uuid references auth.users on delete cascade not null primary key, -- UUID from auth.users
  username    text,
  status      user_status default 'OFFLINE'::public.user_status
);
comment on table public.users is 'Profile data for each user.';
comment on column public.users.id is 'References the internal Supabase Auth user.';

-- CHANNELS
create table public.channels (
  id            bigint generated by default as identity primary key,
  inserted_at   timestamp with time zone default timezone('utc'::text, now()) not null,
  slug          text not null unique,
  created_by    uuid references public.users on delete set null
);
comment on table public.channels is 'Topics and groups.';

-- MESSAGES
create table public.messages (
  id            bigint generated by default as identity primary key,
  inserted_at   timestamp with time zone default timezone('utc'::text, now()) not null,
  message       text,
  user_id       uuid references public.users on delete cascade not null,
  channel_id    bigint references public.channels on delete cascade not null
);
comment on table public.messages is 'Individual messages sent by each user.';

-- MEMBERS: each person's role, by email address (the app-role pattern Tofu's dashboard reads and sets)
create table public.app_members (
  email     text primary key check (email = lower(email)),
  role      text not null check (role in ('admin', 'member', 'viewer')),
  added_at  timestamptz not null default now()
);
comment on table public.app_members is 'Application roles for each user, by email address: admin, member or viewer.';

-- ROLE PERMISSIONS
create table public.role_permissions (
  id           bigint generated by default as identity primary key,
  role         text not null check (role in ('admin', 'member', 'viewer')),
  permission   app_permission not null,
  unique (role, permission)
);
comment on table public.role_permissions is 'Application permissions for each role.';

-- SIGN-UP SWITCH: one row, written by the build from NEXT_PUBLIC_DISABLE_SIGN_UP (tofu/migrate.mjs)
create table public.app_settings (
  id            boolean primary key default true check (id),
  sign_up_open  boolean not null default true,
  updated_at    timestamptz not null default now()
);
comment on table public.app_settings is 'Whether anyone may make an account. Set by the build from NEXT_PUBLIC_DISABLE_SIGN_UP.';

-- The signed-in person's role: their row in app_members, or member when they have none.
create function public.current_app_role()
returns text
language sql stable security definer set search_path = ''
as $$
  select case when auth.uid() is null then null else coalesce(
    (select m.role from public.app_members m join auth.users u on m.email = lower(u.email) where u.id = auth.uid()),
    'member'
  ) end
$$;

-- authorize with role-based access control (RBAC)
create function public.authorize(
  requested_permission public.app_permission
)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1
    from public.role_permissions p
    where p.permission = requested_permission
      and p.role = public.current_app_role()
  )
$$;

-- Secure the tables
alter table public.users enable row level security;
alter table public.channels enable row level security;
alter table public.messages enable row level security;
alter table public.app_members enable row level security;
alter table public.role_permissions enable row level security;
alter table public.app_settings enable row level security;
create policy "Allow logged-in read access" on public.users for select using ( auth.role() = 'authenticated' );
create policy "Allow logged-in read access" on public.channels for select using ( auth.role() = 'authenticated' );
create policy "Allow individual insert access" on public.channels for insert with check ( auth.uid() = created_by and authorize('channels.create') );
create policy "Allow individual delete access" on public.channels for delete using ( auth.uid() = created_by );
create policy "Allow authorized delete access" on public.channels for delete using ( authorize('channels.delete') );
create policy "Allow logged-in read access" on public.messages for select using ( auth.role() = 'authenticated' );
create policy "Allow individual insert access" on public.messages for insert with check ( auth.uid() = user_id and authorize('messages.create') );
create policy "Allow individual update access" on public.messages for update using ( auth.uid() = user_id );
create policy "Allow individual delete access" on public.messages for delete using ( auth.uid() = user_id );
create policy "Allow authorized delete access" on public.messages for delete using ( authorize('messages.delete') );

-- What the Data API's roles may do, which row-level security narrows to each row. The members, permissions and
-- settings tables are read only through the SECURITY DEFINER functions above.
revoke all on table public.users, public.channels, public.messages, public.app_members, public.role_permissions, public.app_settings from anon, authenticated;
grant select on table public.users to authenticated;
grant select, insert, delete on table public.channels to authenticated;
grant select, insert, update, delete on table public.messages to authenticated;
revoke execute on function public.current_app_role(), public.authorize(public.app_permission) from public, anon;
grant execute on function public.current_app_role(), public.authorize(public.app_permission) to authenticated;

-- Send "previous data" on change
alter table public.users replica identity full;
alter table public.channels replica identity full;
alter table public.messages replica identity full;

-- inserts a row into public.users and gives the new person a role: the first account made in the app is its admin,
-- every account after it a member
create function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.users (id, username)
  values (new.id, new.email);

  if new.email is not null then
    -- One new account at a time decides whether it is the first, so two at once cannot both become admin.
    perform pg_advisory_xact_lock(hashtext('public.app_members: first account'));
    insert into public.app_members (email, role)
    values (lower(new.email), case when exists (select 1 from public.app_members) then 'member' else 'admin' end)
    on conflict (email) do nothing;
  end if;

  return new;
end;
$$;

-- trigger the function every time a user is created
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- refuses a new account while sign-up is closed, except one the app's owner adds from Tofu's dashboard, which
-- carries tofu_added_by_owner in its app_metadata (a field the person signing up cannot set)
create function public.refuse_closed_sign_up()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if coalesce(new.raw_app_meta_data ->> 'tofu_added_by_owner', '') = 'true' then
    return new;
  end if;
  if exists (select 1 from public.app_settings where not sign_up_open) then
    raise exception 'Sign-up is closed in this chat: ask its owner to add you.' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

create trigger before_auth_user_created
  before insert on auth.users
  for each row execute procedure public.refuse_closed_sign_up();

-- forgets a removed person's role, so an address that comes back starts as any new account would, never with the
-- admin role it held before
create function public.forget_removed_member()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if old.email is not null then
    delete from public.app_members where email = lower(old.email);
  end if;
  return old;
end;
$$;

create trigger on_auth_user_deleted
  after delete on auth.users
  for each row execute procedure public.forget_removed_member();

/**
 * REALTIME SUBSCRIPTIONS
 * Only allow realtime listening on public tables.
 */

-- the database's own publication, made only where it is missing (a plain PostgreSQL); it is never dropped
do $$
begin
  if not exists (select 1 from pg_catalog.pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
end
$$;

-- add tables to the publication
alter publication supabase_realtime add table public.channels;
alter publication supabase_realtime add table public.messages;
alter publication supabase_realtime add table public.users;
